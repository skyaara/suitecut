import * as z from 'zod'

const count = z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER)
export const NativeStreamingInfoSchema = z.strictObject({
  clientToken: z.string().min(1).max(128),
  id: z.string().min(1).max(128),
  phase: z.enum(['starting', 'streaming', 'reconnecting', 'stopping', 'complete', 'failed']),
  failure: z.string().max(16384),
  diagnostics: z.string().max(8192),
  firstCapturedTimestampMs: z.number().finite().min(-1).optional(),
  attemptNumber: count.optional(),
  reconnectAttempts: count.optional(),
  reconnecting: z.boolean().optional(),
  cumulativeSubmittedFrames: count.optional(),
  cumulativeEncodedFrames: count.optional(),
  cumulativeAudioSubmittedFrames: count.optional(),
  cumulativeMuxedBytes: count.optional(),
  disconnectedVideoFrames: count.optional(),
  disconnectedAudioFrames: count.optional(),
  lastAttemptFailure: z.string().max(16384).optional(),
  attempts: z
    .array(
      z.strictObject({
        number: count,
        encoderPid: z.number().int().nonnegative(),
        firstTimestampMs: z.number().finite().min(-1),
        firstCapturedTimestampMs: z.number().finite().min(-1),
        finishedTimestampMs: z.number().finite().nonnegative(),
        submittedFrames: count,
        encodedFrames: count,
        audioSubmittedFrames: count,
        muxedBytes: count,
        failure: z.string().max(1024),
        diagnostics: z.string().max(1024),
        diagnosticTruncated: z.boolean(),
        childReaped: z.boolean(),
        childExitObserved: z.boolean(),
      }),
    )
    .max(8)
    .optional(),
  firstTimestampMs: z.number().finite().min(-1),
  durationMs: z.number().finite().nonnegative(),
  inputFrames: count,
  submittedFrames: count,
  heldFrames: count,
  supersededFrames: count,
  encodedFrames: count,
  audioInputFrames: count,
  audioSubmittedFrames: count,
  audioGapFrames: count,
  audioOverlapFrames: count,
  pausedAudioFrames: count,
  pausedInputAudioFrames: count,
  switchedAudioFrames: count,
  stoppedAudioFrames: count.optional(),
  stoppedVideoFrames: count.optional(),
  pausedInputVideoFrames: count.optional(),
  capturedFrameBytes: count.optional(),
  peakCapturedFrameBytes: count.optional(),
  captureLatencyMs: z.number().finite().nonnegative().optional(),
  videoIntervalClosureMs: z.number().finite().positive().optional(),
  maxCaptureToPipeMs: z.number().finite().nonnegative().optional(),
  muxedBytes: count,
  encodedProgressObserved: z.boolean(),
  muxedProgressObserved: z.boolean(),
  physicalEncoderPid: z.number().int().nonnegative(),
  selectedPageId: z.number().int().positive().optional(),
  framesPerSecond: z.number().finite().min(1).max(120).optional(),
  timestampMs: z.number().finite().nonnegative().optional(),
})
export type NativeStreamingInfo = z.infer<typeof NativeStreamingInfoSchema>
