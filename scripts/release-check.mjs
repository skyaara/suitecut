// Checks every npm package in the repository before a release, without publishing:
// manifest fields, tarball contents and size, and whether the version is already on npm.
// Usage: node scripts/release-check.mjs [--offline]
import { execFile } from 'node:child_process'
import { readFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import process from 'node:process'

import * as z from 'zod'

const root = resolve(import.meta.dirname, '..')
const offline = process.argv.includes('--offline')
const packages = ['.', 'packages/browser-control', 'packages/shared-browser']

const Manifest = z.object({
  name: z.string(),
  version: z.string().regex(/^\d+\.\d+\.\d+(-[\w.]+)?$/),
  description: z.string().min(20),
  license: z.literal('MIT'),
  homepage: z.string().startsWith('https://'),
  repository: z.object({ url: z.string().min(1) }),
  engines: z.object({ node: z.string() }),
  files: z.array(z.string()).min(1),
  publishConfig: z.object({ access: z.literal('public') }),
})
const Pack = z.array(
  z.object({
    filename: z.string(),
    size: z.number(),
    unpackedSize: z.number(),
    files: z.array(z.object({ path: z.string() })),
  }),
)

// Nothing private, generated by a local run, or belonging to a browser runtime goes to npm.
const forbidden = [
  /^\.suitecut\//,
  /^tests?\//,
  /^node_modules\//,
  /\.env$/,
  /\.(dylib|so|dll|pak)$/,
  /libcef|Chromium Embedded Framework/,
]

/**
 * Runs a command and returns its standard output.
 * @param {string} executable
 * @param {string[]} args
 * @param {string} cwd
 * @returns {Promise<string>}
 */
function run(executable, args, cwd) {
  return new Promise((done, fail) => {
    execFile(executable, args, { cwd, maxBuffer: 64 * 1024 * 1024 }, (error, stdout, stderr) => {
      if (error) fail(new Error(`${executable} ${args.join(' ')} failed\n${stderr || stdout}`))
      else done(stdout)
    })
  })
}

/**
 * Asks npm whether this exact version is already published.
 * @param {string} name
 * @param {string} version
 * @returns {Promise<string>}
 */
async function registryState(name, version) {
  if (offline) return 'not checked'
  let versions
  try {
    versions = z
      .array(z.string())
      .parse([JSON.parse(await run('npm', ['view', name, 'versions', '--json'], root))].flat())
  } catch {
    return 'new package'
  }
  return versions.includes(version)
    ? 'ALREADY PUBLISHED'
    : `new version (npm has ${versions.at(-1)})`
}

let failed = false
for (const directory of packages) {
  const cwd = join(root, directory)
  const manifest = Manifest.safeParse(JSON.parse(await readFile(join(cwd, 'package.json'), 'utf8')))
  if (!manifest.success) {
    failed = true
    process.stderr.write(`${directory}: ${z.prettifyError(manifest.error)}\n`)
    continue
  }
  const { name, version } = manifest.data
  const [pack] = Pack.parse(
    JSON.parse(await run('npm', ['pack', '--dry-run', '--json', '--ignore-scripts'], cwd)),
  )
  const paths = pack.files.map((file) => file.path)
  const problems = [
    ...['README.md', 'LICENSE', 'package.json']
      .filter((file) => !paths.includes(file))
      .map((file) => `missing ${file}`),
    ...paths
      .filter((path) => forbidden.some((pattern) => pattern.test(path)))
      .map((path) => `should not ship ${path}`),
    ...(paths.some((path) => path.startsWith('dist/')) ? [] : ['no dist/ files; build first']),
  ]
  const state = await registryState(name, version)
  if (state === 'ALREADY PUBLISHED') problems.push(`${name}@${version} is already on npm`)
  const size = `${(pack.size / 1024).toFixed(0)} KiB packed, ${(pack.unpackedSize / 1024 / 1024).toFixed(1)} MiB unpacked`
  const mark = problems.length ? '✗' : '✓'
  process.stdout.write(`${mark} ${name}@${version}  ${paths.length} files, ${size}, ${state}\n`)
  for (const problem of problems) process.stdout.write(`    ${problem}\n`)
  failed ||= problems.length > 0
}
process.exitCode = failed ? 1 : 0
