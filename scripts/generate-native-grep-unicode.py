"""Derive ECMAScript Canonicalize tables from public Unicode17 data only.

No platform locale, Python Unicode database, or regex implementation is used.
Inputs are explicit UnicodeData.txt, unconditional SpecialCasing.txt uppercase
mappings, and CaseFolding.txt simple/common mappings. Generated derivatives
retain the separate Unicode LicenseV3 notice and original input hashes.
"""
import argparse
import hashlib
import json
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument('--data-directory', type=Path, required=True)
p.add_argument('--output', type=Path, required=True)
a = p.parse_args()
files = {name:a.data_directory/(name+'-17.0.0.txt') for name in ['UnicodeData','SpecialCasing','CaseFolding']}
upper = {}
for line in files['UnicodeData'].read_text().splitlines():
    fields = line.split(';')
    if fields[12]:
        upper[int(fields[0],16)] = [int(fields[12],16)]
for line in files['SpecialCasing'].read_text().splitlines():
    fields = line.split('#',1)[0].strip().split(';')
    if len(fields)>=5 and not fields[4].strip():
        upper[int(fields[0].strip(),16)] = [int(x,16) for x in fields[3].split()]
legacy = {}
for code, mapped in upper.items():
    if code>65535 or len(mapped)!=1 or mapped[0]>65535 or (code>=128 and mapped[0]<128):
        continue
    if code!=mapped[0]:
        legacy[code] = mapped[0]
assert all(legacy.get(mapped,mapped)==mapped for mapped in legacy.values())
fold = {}
for line in files['CaseFolding'].read_text().splitlines():
    fields = line.split('#',1)[0].strip().split(';')
    if len(fields)>=3 and fields[1].strip() in ['C','S']:
        mapped = fields[2].split()
        assert len(mapped)==1
        code,value = int(fields[0].strip(),16),int(mapped[0],16)
        if code!=value:
            fold[code] = value
assert all(fold.get(mapped,mapped)==mapped for mapped in fold.values())
lines = ['// SPDX-License-Identifier: MIT AND Unicode-3.0', '// Generated by scripts/generate-native-grep-unicode.py from Unicode17.0.0.',
    '// Modified Unicode data derivative: ECMAScript Canonicalize projections.',
    '// Unicode LicenseV3: see unicode_data_LICENSE.txt. No external regex code.',
    '#pragma once','#include <array>','#include <cstddef>','#include <cstdint>',
    'namespace suitecut::runner::grep_unicode {',
    'struct Mapping {uint32_t from,to;};']
for name,mapping in [('Legacy',legacy),('Simple',fold)]:
    lines += ['inline constexpr std::array<Mapping,'+str(len(mapping))+'> k'+name+'Mappings{{']
    lines += ['  {0x%04x,0x%04x},'%(code,value) for code,value in sorted(mapping.items())]
    lines += ['}};']
lines += ['template<std::size_t N> inline uint32_t Lookup(const std::array<Mapping,N>& table,uint32_t code){',
    '  std::size_t first=0,last=N;',
    '  while(first<last){const auto middle=first+(last-first)/2;if(table[middle].from<code)first=middle+1;else last=middle;}',
    '  return first<N&&table[first].from==code?table[first].to:code;',
    '}',
    "inline uint16_t Legacy(uint16_t unit){if(unit<128)return unit>='a'&&unit<='z'?static_cast<uint16_t>(unit-32):unit;return static_cast<uint16_t>(Lookup(kLegacyMappings,unit));}",
    'inline uint32_t Simple(uint32_t point){return Lookup(kSimpleMappings,point);}',
    '}  // namespace suitecut::runner::grep_unicode','']
a.output.write_text('\n'.join(lines))
manifest = {'version':'17.0.0','standard':'https://tc39.es/ecma262/#sec-runtime-semantics-canonicalize-ch',
    'legacyMappings':len(legacy),'simpleMappings':len(fold),
    'inputs':{str(path):hashlib.sha256(path.read_bytes()).hexdigest() for path in files.values()},
    'generatorSHA256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    'outputSHA256':hashlib.sha256(a.output.read_bytes()).hexdigest()}
a.output.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest,indent=2))
